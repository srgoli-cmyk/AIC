#!/usr/bin/env node
// Fills extension/vendor/ with everything the standalone extension loads at run time, so no page or
// worker ever fetches code or models from another site (Chrome Web Store rule for Manifest V3, and
// it keeps lecture text on the device):
//   transformers/  transformers.js 3.8.1 + its ONNX Runtime WebAssembly files (from npm)
//   models/        Xenova/bge-small-en-v1.5, 8-bit ONNX, pinned revision, checked by SHA-256
//   katex/         KaTeX 0.16.11 (math in answers)
//   fonts/         Inter Tight + JetBrains Mono (latin), with fonts.css
// Run `npm ci` in extension/ first (make vendor does both). The folder is git-ignored: it is
// rebuilt from pinned versions, never committed.
import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "extension");
const NM = join(ROOT, "node_modules");
const OUT = join(ROOT, "vendor");

const MODEL = "Xenova/bge-small-en-v1.5";
const MODEL_REVISION = "ea104dacec62c0de699686887e3f920caeb4f3e3";
const MODEL_FILES = {
  "config.json": "fa73f90bf92c8cace1fbcb709626306f2bdbc9ea3e5b5f94b440df9b6aa56350",
  "tokenizer.json": "d241a60d5e8f04cc1b2b3e9ef7a4921b27bf526d9f6050ab90f9267a1f9e5c66",
  "tokenizer_config.json": "9261e7d79b44c8195c1cada2b453e55b00aeb81e907a6664974b4d7776172ab3",
  "special_tokens_map.json": "b6d346be366a7d1d48332dbc9fdf3bf8960b5d879522b7799ddba59e76237ee3",
  "onnx/model_quantized.onnx": "6c9c6101a956d62dfb5e7190c538226c0c5bb9cb27b651234b6df063ee7dbfe4",
};

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

async function exists(p) {
  try {
    await stat(p);
    return true;
  } catch {
    return false;
  }
}

async function copy(from, to) {
  await mkdir(dirname(to), { recursive: true });
  await copyFile(from, to);
}

async function vendorTransformers() {
  const dist = join(NM, "@huggingface/transformers/dist");
  const pkg = JSON.parse(await readFile(join(NM, "@huggingface/transformers/package.json"), "utf8"));
  if (pkg.version !== "3.8.1") throw new Error(`expected @huggingface/transformers 3.8.1, found ${pkg.version}; run npm ci`);
  for (const f of ["transformers.min.js", "ort-wasm-simd-threaded.jsep.mjs", "ort-wasm-simd-threaded.jsep.wasm"]) {
    await copy(join(dist, f), join(OUT, "transformers", f));
  }
  await copy(join(NM, "@huggingface/transformers/LICENSE"), join(OUT, "transformers", "LICENSE"));
}

async function vendorModel() {
  for (const [file, want] of Object.entries(MODEL_FILES)) {
    const dest = join(OUT, "models", MODEL, file);
    if ((await exists(dest)) && sha256(await readFile(dest)) === want) continue;
    const url = `https://huggingface.co/${MODEL}/resolve/${MODEL_REVISION}/${file}`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`download failed (${res.status}): ${file}`);
    const buf = Buffer.from(await res.arrayBuffer());
    const got = sha256(buf);
    if (got !== want) throw new Error(`checksum mismatch for ${file}: ${got}`);
    await mkdir(dirname(dest), { recursive: true });
    await writeFile(dest, buf);
  }
  await writeFile(
    join(OUT, "models", MODEL, "SOURCE.txt"),
    `https://huggingface.co/${MODEL} at revision ${MODEL_REVISION}\nConverted from BAAI/bge-small-en-v1.5 (MIT License).\n`,
  );
}

async function vendorKatex() {
  const dist = join(NM, "katex/dist");
  const pkg = JSON.parse(await readFile(join(NM, "katex/package.json"), "utf8"));
  if (pkg.version !== "0.16.11") throw new Error(`expected katex 0.16.11, found ${pkg.version}; run npm ci`);
  for (const f of ["katex.min.js", "katex.min.css"]) await copy(join(dist, f), join(OUT, "katex", f));
  const css = await readFile(join(dist, "katex.min.css"), "utf8");
  const fonts = [...new Set([...css.matchAll(/url\(fonts\/([A-Za-z0-9_-]+\.woff2)\)/g)].map((m) => m[1]))];
  for (const f of fonts) await copy(join(dist, "fonts", f), join(OUT, "katex", "fonts", f));
  await copy(join(NM, "katex/LICENSE"), join(OUT, "katex", "LICENSE"));
}

async function vendorFonts() {
  const faces = [
    ["Inter Tight", "@fontsource/inter-tight", "inter-tight", [400, 500, 600, 700]],
    ["JetBrains Mono", "@fontsource/jetbrains-mono", "jetbrains-mono", [400]],
  ];
  let css = "/* Generated by scripts/vendor_extension.mjs (SIL Open Font License 1.1). */\n";
  for (const [family, pkg, slug, weights] of faces) {
    for (const w of weights) {
      const file = `${slug}-latin-${w}-normal.woff2`;
      await copy(join(NM, pkg, "files", file), join(OUT, "fonts", file));
      css += `@font-face{font-family:"${family}";font-style:normal;font-display:swap;font-weight:${w};src:url(${file}) format("woff2");}\n`;
    }
    await copy(join(NM, pkg, "LICENSE"), join(OUT, "fonts", `LICENSE-${slug}`));
  }
  await writeFile(join(OUT, "fonts", "fonts.css"), css);
}

if (process.argv.includes("--clean")) await rm(OUT, { recursive: true, force: true });
await vendorTransformers();
await vendorKatex();
await vendorFonts();
await vendorModel();
console.log("vendor: ok");
